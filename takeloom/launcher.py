"""Desktop launchers for `takeloom ui`, so it opens like any other app.

takeloom itself is always installed with pipx; a launcher is only a thin
shell around the pipx-installed `takeloom ui`, so updating (update_check.py's
`pipx install --force`) never needs the launcher touched.

- macOS: Takeloom.app — Info.plist, icon, and a shell script that runs
  `takeloom ui`, first installing takeloom with pipx if it isn't yet. That
  makes the .app self-sufficient, so it can ship on its own in a
  drag-to-Applications disk image (build_macos_dmg, see
  scripts/build_macos_dmg.py).
- Linux: the .desktop entry (ui/desktop_entry.py, which `takeloom ui` also
  keeps current on every launch) plus a copy on the desktop.

`takeloom install-launcher` installs whichever fits this machine.
"""

from __future__ import annotations

import os
import plistlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_URL = "https://github.com/priestc/takeloom.git"
ICON_PATH = Path(__file__).resolve().parent / "data" / "icon.png"
APP_NAME = "Takeloom"

# A Finder-launched app gets PATH=/usr/bin:/bin:/usr/sbin:/sbin — none of
# where pipx or its `takeloom` live.
_MAC_LAUNCH_SCRIPT = f"""#!/bin/bash
# Takeloom.app launcher: runs the pipx-installed `takeloom ui`, installing
# it with pipx first if needed. Generated by takeloom/launcher.py.
export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
LOG="$HOME/Library/Logs/takeloom-ui.log"
mkdir -p "$HOME/Library/Logs"

alert() {{
    /usr/bin/osascript -e "display alert \\"$1\\" message \\"$2\\" as critical" >/dev/null 2>&1
}}

if ! command -v takeloom >/dev/null 2>&1; then
    if ! command -v pipx >/dev/null 2>&1; then
        alert "Takeloom needs pipx" "Install it with Homebrew (brew install pipx python-tk), then open Takeloom again."
        exit 1
    fi
    /usr/bin/osascript -e 'display notification "Installing Takeloom with pipx — this takes a minute or two." with title "Takeloom"'
    if ! pipx install "git+{REPO_URL}" >>"$LOG" 2>&1; then
        alert "Takeloom couldn't be installed" "pipx install failed — see $LOG"
        exit 1
    fi
fi

exec takeloom ui >>"$LOG" 2>&1
"""


class LauncherError(Exception):
    pass


def install_launcher(log=print) -> None:
    """Install the launcher that fits this platform."""
    if os.environ.get("FLATPAK_ID"):
        raise LauncherError("This is the Flatpak: it's already in your applications menu.")
    if sys.platform == "darwin":
        apps = Path("/Applications")
        dest = apps if os.access(apps, os.W_OK) else Path.home() / "Applications"
        app = build_macos_app(dest)
        log(f"Installed {app} — open Takeloom from Launchpad, Spotlight, or the Applications folder.")
    elif sys.platform.startswith("linux"):
        for path in install_linux_launcher():
            log(f"Installed {path}")
        log("Takeloom is now in your applications menu (and on the desktop).")
    else:
        raise LauncherError(f"No desktop launcher for this platform ({sys.platform}).")


# --- macOS ---

def build_macos_app(dest_dir: Path) -> Path:
    """Write Takeloom.app into dest_dir (replacing any earlier one) and
    return its path. macOS only: the icon goes through iconutil."""
    app = dest_dir / f"{APP_NAME}.app"
    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp) / app.name
        contents = staged / "Contents"
        (contents / "MacOS").mkdir(parents=True)
        (contents / "Resources").mkdir()

        with open(contents / "Info.plist", "wb") as f:
            plistlib.dump({
                "CFBundleName": APP_NAME,
                "CFBundleDisplayName": APP_NAME,
                "CFBundleIdentifier": "com.github.priestc.takeloom",
                "CFBundleExecutable": APP_NAME,
                "CFBundleIconFile": "takeloom",
                "CFBundlePackageType": "APPL",
                "CFBundleShortVersionString": "1.0",
                "CFBundleVersion": "1",
                "LSMinimumSystemVersion": "11.0",
                "NSHighResolutionCapable": True,
                # macOS attributes the takeloom process's mic/camera use to
                # this app, and silently denies it without these.
                "NSMicrophoneUsageDescription": "Takeloom records your instruments.",
                "NSCameraUsageDescription": "Takeloom records video of your sessions.",
            }, f)

        script = contents / "MacOS" / APP_NAME
        script.write_text(_MAC_LAUNCH_SCRIPT)
        script.chmod(0o755)
        _write_icns(contents / "Resources" / "takeloom.icns")

        # Ad-hoc signature: without any, Apple Silicon Gatekeeper treats
        # the bundle as damaged rather than merely unidentified.
        subprocess.run(["codesign", "--force", "--deep", "-s", "-", str(staged)],
                       capture_output=True, check=False)

        dest_dir.mkdir(parents=True, exist_ok=True)
        if app.exists():
            shutil.rmtree(app)
        shutil.copytree(staged, app, symlinks=True)
    # Let Finder/Dock notice the (new) icon without a logout.
    subprocess.run(["touch", str(app)], check=False)
    return app


def _write_icns(dest: Path) -> None:
    from PIL import Image

    source = Image.open(ICON_PATH).convert("RGBA")
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "takeloom.iconset"
        iconset.mkdir()
        for size in (16, 32, 128, 256, 512):
            for scale in (1, 2):
                px = size * scale
                name = f"icon_{size}x{size}{'@2x' if scale == 2 else ''}.png"
                source.resize((px, px), Image.LANCZOS).save(iconset / name)
        result = subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(dest)],
                                capture_output=True, text=True)
        if result.returncode != 0:
            raise LauncherError(f"iconutil failed: {result.stderr.strip()}")


def build_macos_dmg(output: Path) -> Path:
    """A disk image holding Takeloom.app next to an Applications shortcut —
    the usual drag-to-install. The .app installs takeloom itself (via pipx)
    on first open, so the image is all a new Mac needs."""
    output = output.resolve()
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / APP_NAME
        root.mkdir()
        build_macos_app(root)
        (root / "Applications").symlink_to("/Applications")
        output.parent.mkdir(parents=True, exist_ok=True)
        result = subprocess.run(
            ["hdiutil", "create", "-volname", APP_NAME, "-srcfolder", str(root),
             "-ov", "-format", "UDZO", str(output)],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            raise LauncherError(f"hdiutil failed: {result.stderr.strip()}")
    return output


# --- Linux ---

def install_linux_launcher() -> list[Path]:
    """The applications-menu entry, plus a copy on the desktop if there is
    one. Returns what was written."""
    from .ui.desktop_entry import desktop_file_path, install_desktop_entry

    install_desktop_entry()
    written = [desktop_file_path()]
    desktop_dir = _xdg_desktop_dir()
    if desktop_dir is not None and desktop_dir.is_dir():
        shortcut = desktop_dir / "takeloom.desktop"
        shutil.copyfile(desktop_file_path(), shortcut)
        shortcut.chmod(0o755)
        # GNOME won't launch a desktop-folder .desktop file until it's
        # marked trusted ("Allow Launching").
        if shutil.which("gio"):
            subprocess.run(["gio", "set", str(shortcut), "metadata::trusted", "true"],
                           capture_output=True, check=False)
        written.append(shortcut)
    return written


def _xdg_desktop_dir() -> Path | None:
    if shutil.which("xdg-user-dir"):
        result = subprocess.run(["xdg-user-dir", "DESKTOP"], capture_output=True, text=True)
        path = result.stdout.strip()
        if result.returncode == 0 and path and Path(path) != Path.home():
            return Path(path)
    fallback = Path.home() / "Desktop"
    return fallback if fallback.is_dir() else None
